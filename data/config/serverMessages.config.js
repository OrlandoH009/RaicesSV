const translateMessage = (message, lang) => {
    if (lang !== 'en' || typeof message !== 'string') return message;
    if (Object.prototype.hasOwnProperty.call(EXACT_EN, message)) return EXACT_EN[message];
    for (const [pattern, build] of PATTERNS_EN) {
        const match = pattern.exec(message);
        if (match) return build(...match.slice(1));
    }
    return message;
};

module.exports = { translateMessage };
